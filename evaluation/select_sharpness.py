# Chooses how much to sharpen the simulation's game probabilities. For each season the
# model is trained as the simulation trains it at a February 1 cutoff, and every candidate
# sharpness is scored on the real results of the games played after that date. Candidates
# and the rule are fixed below; the final season is reported but not used to choose.
# Run from the repo root:
#   python -m evaluation.select_sharpness --output docs/sharpness.md
import argparse
from pathlib import Path

import numpy as np
from sklearn.metrics import log_loss

from models.train_win_probability import load_training_data
from simulation.monte_carlo import get_db_connection, get_win_probabilities, sharpen

VALIDATION_SEASONS = ["2022-23", "2023-24", "2024-25"]
TEST_SEASON = "2025-26"
CANDIDATES = [1.0, 1.25, 1.5, 1.75, 2.0]
# Log-loss differences smaller than this count as a tie, won by the smaller sharpness.
TIE_TOLERANCE = 0.002


def cutoff_for(season):
    """February 1 of the season's second calendar year, e.g. 2026-02-01 for 2025-26."""
    return f"{int(season[:4]) + 1}-02-01"


def remaining_games(conn, season):
    """(unsharpened home-win probabilities, actual results) for every game on or after the
    season's cutoff, predicted exactly as the simulation predicts them."""
    probs, *_ = get_win_probabilities(conn, season, cutoff_for(season), sharpness=1.0)
    outcomes = load_training_data(conn, season).set_index("game_id")["home_win"]
    game_ids = list(probs)
    return np.array([probs[g] for g in game_ids]), outcomes.loc[game_ids].to_numpy()


def score(probs, outcomes):
    """{sharpness: log loss} for every candidate."""
    return {k: log_loss(outcomes, sharpen(probs, k), labels=[0, 1]) for k in CANDIDATES}


def choose(losses):
    """The smallest candidate within TIE_TOLERANCE of the lowest log loss."""
    best = min(losses.values())
    return min(k for k, loss in losses.items() if loss <= best + TIE_TOLERANCE)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", help="optional Markdown file to write the results to")
    args = parser.parse_args()

    conn = get_db_connection()
    per_season = {s: remaining_games(conn, s) for s in [*VALIDATION_SEASONS, TEST_SEASON]}
    conn.close()

    validation_probs = np.concatenate([per_season[s][0] for s in VALIDATION_SEASONS])
    validation_outcomes = np.concatenate([per_season[s][1] for s in VALIDATION_SEASONS])
    validation = score(validation_probs, validation_outcomes)
    test = score(*per_season[TEST_SEASON])
    chosen = choose(validation)

    lines = [
        "## Sharpening the simulation's game probabilities",
        "",
        "Generated by `python -m evaluation.select_sharpness --output docs/sharpness.md`. "
        "Each season's model is trained as the simulation trains it on February 1, and "
        "each sharpness is scored by log loss on the real results of the games after that "
        f"date. Chosen on {', '.join(VALIDATION_SEASONS)} ({len(validation_outcomes)} games; "
        f"ties within {TIE_TOLERANCE} go to the smaller value) and reported once on "
        f"{TEST_SEASON} ({len(per_season[TEST_SEASON][1])} games). Lower is better; "
        "sharpness 1.0 is the unchanged model.",
        "",
        "| Sharpness | Validation log loss | Test log loss |",
        "|---|---|---|",
    ]
    for k in CANDIDATES:
        label = f"{k}" + (" **(chosen)**" if k == chosen else "")
        lines.append(f"| {label} | {validation[k]:.4f} | {test[k]:.4f} |")
    report = "\n".join(lines)
    print(report)
    if args.output:
        Path(args.output).parent.mkdir(parents=True, exist_ok=True)
        Path(args.output).write_text(report + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
