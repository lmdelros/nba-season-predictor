# Backtests the Monte Carlo season simulation: pretend it is --cutoff-date, project
# final win totals, and compare them with what actually happened. Reads from the
# database only; nothing is saved. Run from the repo root:
#   python -m evaluation.backtest_simulation --season 2025-26 --cutoff-date 2026-02-01
import argparse
from pathlib import Path

import pandas as pd

from simulation.monte_carlo import (
    compute_current_standings,
    compute_pairwise_win_probs,
    get_db_connection,
    get_win_probabilities,
    load_played_games,
    load_remaining_games,
    load_team_snapshot_features,
    run_simulations,
)

GAMES_PER_SEASON = 82


def load_actual_final_wins(conn, season):
    """Each team's real final regular-season win total."""
    return compute_current_standings(load_played_games(conn, season, "9999-12-31"))


def pace_projection(current_wins, played_games):
    """Naive baseline: each team keeps its win % at the cutoff for all 82 games."""
    games_played = pd.concat([played_games["home_team_id"], played_games["away_team_id"]])
    counts = games_played.value_counts()
    return {
        team_id: wins / counts[team_id] * GAMES_PER_SEASON
        for team_id, wins in current_wins.items()
    }


def actual_playoff_teams(final_wins, teams_df):
    """Top 8 by real final wins in each conference, the same rule the simulation uses."""
    df = teams_df.assign(wins=teams_df["team_id"].map(final_wins))
    return set(df.sort_values("wins", ascending=False).groupby("conference").head(8)["team_id"])


def compare(projected, actual):
    """Rank correlation, mean absolute error, and bias (projected minus actual) in wins."""
    df = pd.DataFrame({"projected": pd.Series(projected), "actual": pd.Series(actual)})
    # Spearman correlation is the Pearson correlation of the ranks.
    rank_corr = df["projected"].rank().corr(df["actual"].rank())
    error = df["projected"] - df["actual"]
    return {"rank_corr": rank_corr, "mae": error.abs().mean(), "bias": error.mean()}


def run_backtest(conn, season, cutoff_date, n_simulations, seed):
    played = load_played_games(conn, season, cutoff_date)
    remaining = load_remaining_games(conn, season, cutoff_date)
    current_wins = compute_current_standings(played)
    win_probs, model, scaler, fills = get_win_probabilities(conn, season, cutoff_date)
    teams_df = pd.read_sql("SELECT team_id, conference FROM teams", conn)
    snapshot = load_team_snapshot_features(conn, season, cutoff_date)
    pairwise_probs = compute_pairwise_win_probs(
        teams_df["team_id"], snapshot, model, scaler, fills
    )
    results = run_simulations(
        current_wins, remaining, win_probs, teams_df, pairwise_probs,
        n_simulations=n_simulations, seed=seed,
    )

    actual = load_actual_final_wins(conn, season)
    simulated = dict(zip(results["team_id"], results["avg_wins"]))
    playoff_teams = actual_playoff_teams(actual, teams_df)
    predicted_in = set(results.loc[results["playoff_pct"] >= 0.5, "team_id"])

    return {
        "played": len(played),
        "remaining": len(remaining),
        "simulation": compare(simulated, actual),
        "pace": compare(pace_projection(current_wins, played), actual),
        "playoff_hits": len(playoff_teams & predicted_in),
        "playoff_total": len(playoff_teams),
    }


def to_markdown(season, cutoff_date, n_simulations, seed, result):
    sim, pace = result["simulation"], result["pace"]
    return "\n".join([
        "## Season simulation backtest",
        "",
        "Generated by `python -m evaluation.backtest_simulation "
        f"--season {season} --cutoff-date {cutoff_date} --n-simulations {n_simulations} "
        "--output docs/backtest.md`.",
        "",
        f"Pretend it is {cutoff_date}: {result['played']} games are already played and "
        f"{result['remaining']} remain. The simulation projects each team's final win total "
        f"({n_simulations:,} runs, seed {seed}), which is compared with the real final totals.",
        "",
        "| Method | Rank correlation | Mean abs. error (wins) | Bias (wins) |",
        "|---|---|---|---|",
        f"| Keep cutoff win % for all 82 games | {pace['rank_corr']:.3f} | "
        f"{pace['mae']:.2f} | {pace['bias']:+.2f} |",
        f"| Monte Carlo simulation (this project) | {sim['rank_corr']:.3f} | "
        f"{sim['mae']:.2f} | {sim['bias']:+.2f} |",
        "",
        f"Playoff teams given a 50%+ chance by the simulation: "
        f"{result['playoff_hits']} of the {result['playoff_total']} real playoff teams "
        "(top 8 per conference by wins; the play-in tournament is not modeled).",
    ])


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--season", default="2025-26")
    parser.add_argument("--cutoff-date", default="2026-02-01")
    parser.add_argument("--n-simulations", type=int, default=10000)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--output", help="optional Markdown file to write the results to")
    args = parser.parse_args()

    conn = get_db_connection()
    result = run_backtest(conn, args.season, args.cutoff_date, args.n_simulations, args.seed)
    conn.close()

    report = to_markdown(args.season, args.cutoff_date, args.n_simulations, args.seed, result)
    print(report)
    if args.output:
        Path(args.output).parent.mkdir(parents=True, exist_ok=True)
        Path(args.output).write_text(report + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
