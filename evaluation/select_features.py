# Chooses the win model's feature set using training seasons only, so the held-out
# test season (2025-26) plays no part in the choice. Each round trains on every
# earlier season and validates on the next one ("forward chaining"). The candidate
# sets and the decision rule are fixed below, before any results are seen.
# Run from the repo root:
#   python -m evaluation.select_features --output docs/feature_selection.md
import argparse
from pathlib import Path

import pandas as pd

from evaluation.evaluate_win_model import score
from models.train_win_probability import (
    B2B_COLUMNS,
    MARGIN_COLUMNS,
    ORIGINAL_FEATURE_COLUMNS,
    REST_COLUMNS,
    apply_imputer,
    fit_imputer,
    get_db_connection,
    load_training_data,
    train_model,
)

SEASONS = ["2021-22", "2022-23", "2023-24", "2024-25"]
CANDIDATES = {
    "A: current 13 features": ORIGINAL_FEATURE_COLUMNS,
    "B: current 13 + season margin": ORIGINAL_FEATURE_COLUMNS + MARGIN_COLUMNS,
    "C: season margin only": MARGIN_COLUMNS,
    "D: season margin + rest/back-to-back": MARGIN_COLUMNS + REST_COLUMNS + B2B_COLUMNS,
}
# Log-loss differences smaller than this are treated as a tie, won by the smaller set.
TIE_TOLERANCE = 0.002


def forward_chain_folds(df, seasons):
    """(validation season, train rows, validation rows) for each season after the first,
    training on every earlier season."""
    for i in range(1, len(seasons)):
        train = df[df["season"].isin(seasons[:i])]
        val = df[df["season"] == seasons[i]]
        yield seasons[i], train, val


def fit_and_score(train_df, val_df, columns):
    """Trains the project's logistic regression on columns and scores the validation rows."""
    fills = fit_imputer(train_df)
    model, scaler = train_model(apply_imputer(train_df, fills), columns)
    X_val = apply_imputer(val_df, fills)[columns].astype(float)
    probs = model.predict_proba(scaler.transform(X_val))[:, 1]
    return score(val_df["home_win"], probs)


def evaluate_candidates(df, seasons):
    rows = []
    for name, columns in CANDIDATES.items():
        for val_season, train_df, val_df in forward_chain_folds(df, seasons):
            rows.append({
                "candidate": name, "n_features": len(columns), "val_season": val_season,
                "val_games": len(val_df), **fit_and_score(train_df, val_df, columns),
            })
    return pd.DataFrame(rows)


def choose(summary):
    """Lowest mean validation log loss; anything within TIE_TOLERANCE of it counts as a
    tie, and the tie goes to the candidate with the fewest features."""
    best = summary["log_loss"].min()
    tied = summary[summary["log_loss"] <= best + TIE_TOLERANCE]
    return tied.sort_values(["n_features", "log_loss"]).index[0]


def to_markdown(results, summary, chosen, seasons):
    lines = [
        "## Win model feature selection",
        "",
        "Generated by `python -m evaluation.select_features --output "
        "docs/feature_selection.md`. Uses only "
        f"{seasons[0]} to {seasons[-1]}; the 2025-26 test season is not loaded.",
        "",
        "Each round trains on every earlier season and validates on the next one. "
        f"The winner has the lowest mean validation log loss; candidates within "
        f"{TIE_TOLERANCE} of it count as tied, and a tie goes to the smaller feature set.",
        "",
        "| Candidate | Features | Mean log loss | Mean accuracy | Mean Brier |",
        "|---|---|---|---|---|",
    ]
    for name, row in summary.iterrows():
        marker = " **(chosen)**" if name == chosen else ""
        lines.append(
            f"| {name}{marker} | {int(row.n_features)} | {row.log_loss:.4f} | "
            f"{row.accuracy:.1%} | {row.brier:.4f} |"
        )
    lines += [
        "",
        "Per validation season (log loss):",
        "",
        "| Candidate | " + " | ".join(results["val_season"].unique()) + " |",
        "|---|" + "---|" * results["val_season"].nunique(),
    ]
    pivot = results.pivot(index="candidate", columns="val_season", values="log_loss")
    for name in summary.index:
        lines.append(f"| {name} | " + " | ".join(f"{v:.4f}" for v in pivot.loc[name]) + " |")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", help="optional Markdown file to write the results to")
    args = parser.parse_args()

    conn = get_db_connection()
    df = pd.concat(
        [load_training_data(conn, s).assign(season=s) for s in SEASONS], ignore_index=True
    )
    conn.close()

    results = evaluate_candidates(df, SEASONS)
    summary = results.groupby("candidate", sort=False).agg(
        n_features=("n_features", "first"), log_loss=("log_loss", "mean"),
        accuracy=("accuracy", "mean"), brier=("brier", "mean"),
    )
    report = to_markdown(results, summary, choose(summary), SEASONS)
    print(report)
    if args.output:
        Path(args.output).parent.mkdir(parents=True, exist_ok=True)
        Path(args.output).write_text(report + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
